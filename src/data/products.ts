export const MODEST_PRODUCTS = PRODUCTS.filter(
  (p) => p.category === "Modest Wear" || p.keywords.includes("modest"),
);

export const getProduct = (id: string) => PRODUCTS.find((p) => p.id === id);

export const effectivePrice = (p: Product) => p.salePrice ?? p.price;

export const formatPrice = (value: number) =>
  new Intl.NumberFormat("en-US", {
    style: "currency",
    currency: "USD",
    minimumFractionDigits: 0,
  }).format(value);

export const searchProducts = (query: string) => {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  return PRODUCTS.filter((p) =>
    [p.name, p.category, p.collection, p.description, ...p.keywords]
      .join(" ")
      .toLowerCase()
      .includes(q),
  );
};
